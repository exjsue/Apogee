// Writes sw-manifest.js: the list of files the service worker precaches and the
// cache version. Node built-ins only.
// Usage: node tools/build-sw-manifest.js     (run it after changing any app file)
//
// The list is not typed in by hand. It is found by following what the app loads:
// index.html (its scripts, stylesheets, manifest and icons), every module those
// scripts import, and the icons named in the manifest. The version is a SHA-256
// over the content of every listed file and of sw.js, so any change to the app
// gives a new version, and with it a new cache.
//
// Line endings are normalized before hashing (text files only), so the version
// is the same whether a file was saved with LF or CRLF line endings.
//
// tests/sw-manifest.test.js fails if sw-manifest.js is not exactly what this
// script would write now.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_ROOT = path.resolve(here, "..");
export const MANIFEST_FILE = "sw-manifest.js";
const WORKER_FILE = "sw.js";
const HTML_ENTRY = "index.html";
const WEB_MANIFEST = "manifest.webmanifest";

const toPosix = (p) => p.split(path.sep).join("/");

function readIfExists(file, from) {
  if (!fs.existsSync(file)) throw new Error(`${from} refers to ${toPosix(file)}, which does not exist`);
  return fs.readFileSync(file);
}

// Relative specifiers of static imports, re-exports and import() in a module.
function importsOf(source) {
  const found = [];
  for (const m of source.matchAll(/(?:^|\n)\s*(?:import|export)\b[^;]*?\bfrom\s*["']([^"']+)["']/g)) found.push(m[1]);
  for (const m of source.matchAll(/(?:^|\n)\s*import\s*["']([^"']+)["']/g)) found.push(m[1]);
  for (const m of source.matchAll(/\bimport\s*\(\s*["']([^"']+)["']/g)) found.push(m[1]);
  return found;
}

// Every file the app loads, as paths relative to the root ("src/ui/main.js"), sorted.
export function findPrecacheFiles(root = DEFAULT_ROOT) {
  const files = new Set([HTML_ENTRY]);
  const html = readIfExists(path.join(root, HTML_ENTRY), "the build").toString("utf8");

  const references = [];
  for (const m of html.matchAll(/<link\b[^>]*\bhref="([^"]*)"/gi)) references.push(m[1]);
  for (const m of html.matchAll(/<script\b[^>]*\bsrc="([^"]*)"/gi)) references.push(m[1]);
  const scripts = [...html.matchAll(/<script\b[^>]*\bsrc="([^"]*)"/gi)].map((m) => m[1]);

  for (const reference of references) {
    if (reference.startsWith("data:")) continue; // inline, nothing to fetch
    if (!reference.startsWith("./")) throw new Error(`${HTML_ENTRY} refers to "${reference}"; every path must be relative and start with ./`);
    readIfExists(path.join(root, reference), HTML_ENTRY);
    files.add(toPosix(path.normalize(reference)));
  }

  const queue = scripts.map((script) => path.normalize(script));
  const seen = new Set();
  while (queue.length > 0) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    files.add(toPosix(file));
    for (const specifier of importsOf(readIfExists(path.join(root, file), file).toString("utf8"))) {
      if (!specifier.startsWith("./") && !specifier.startsWith("../")) {
        throw new Error(`${toPosix(file)} imports "${specifier}"; every import in the app must be relative`);
      }
      queue.push(path.normalize(path.join(path.dirname(file), specifier)));
    }
  }

  if (files.has(WEB_MANIFEST)) {
    const manifest = JSON.parse(readIfExists(path.join(root, WEB_MANIFEST), HTML_ENTRY).toString("utf8"));
    for (const icon of manifest.icons ?? []) {
      readIfExists(path.join(root, path.dirname(WEB_MANIFEST), icon.src), WEB_MANIFEST);
      files.add(toPosix(path.normalize(path.join(path.dirname(WEB_MANIFEST), icon.src))));
    }
  }
  return [...files].sort();
}

const sha256 = (buffer) => crypto.createHash("sha256").update(buffer).digest("hex");

// Text files hash the same with LF and CRLF line endings; images hash as they are.
function contentHash(root, file) {
  const buffer = fs.readFileSync(path.join(root, file));
  return sha256(file.endsWith(".png") ? buffer : Buffer.from(buffer.toString("utf8").replace(/\r\n?/g, "\n")));
}

export function buildManifest(root = DEFAULT_ROOT) {
  const files = findPrecacheFiles(root);
  const hashed = [...files, WORKER_FILE].map((file) => `${file}\0${contentHash(root, file)}\n`).join("");
  return { version: sha256(Buffer.from(hashed)), files: files.map((file) => `./${file}`) };
}

export function manifestSource({ version, files }) {
  return [
    "// GENERATED by tools/build-sw-manifest.js. Do not edit by hand.",
    "// After changing any file the app loads, or sw.js, run: node tools/build-sw-manifest.js",
    "self.GYMAPP_PRECACHE = {",
    `  version: "${version}",`,
    "  files: [",
    ...files.map((file) => `    "${file}",`),
    "  ],",
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const manifest = buildManifest();
  fs.writeFileSync(path.join(DEFAULT_ROOT, MANIFEST_FILE), manifestSource(manifest));
  console.log(`wrote ${MANIFEST_FILE}: version ${manifest.version.slice(0, 8)}…, ${manifest.files.length} files`);
}
